def draw_cards(n:int):
    cards = random.sample(TAROT, k=min(n, len(TAROT)))
    out = []
    for c in cards:
        rev = random.choice([True, False])
        pos = "перевёрнутая" if rev else "прямая"
        meaning = c["reversed"] if rev else c["upright"]
        out.append((c["name"], c["suit"], pos, meaning, c["advice"]))
    return out

