def get_daily_horoscope(sign, date_str):
    """Получить уникальный гороскоп для знака на дату"""
    if sign not in DAILY_HOROSCOPES:
        return f"🌟 Гороскоп для {sign} на {date_str}\n\n✨ Звёзды говорят: сегодня твой день!"
    
    # Создаем уникальный seed на основе даты и знака
    unique_seed = hash(f"{sign}_{date_str}") % len(DAILY_HOROSCOPES[sign])
    return DAILY_HOROSCOPES[sign][unique_seed]

async def send_daily_horoscopes():
    """Отправить ежедневные гороскопы всем подписчикам"""
    today = date.today().strftime("%Y-%m-%d")
    
    # Очищаем старые записи
    if today not in SENT_HOROSCOPES:
        SENT_HOROSCOPES[today] = set()
    
    sent_count = 0
    for user_id, subscription in SUBSCRIPTIONS.items():
        if not subscription.get("enabled", False):
            continue
            
        if user_id in SENT_HOROSCOPES[today]:
            continue
            
        sign = subscription.get("sign")
        if not sign:
            continue
            
        try:
            horoscope = get_daily_horoscope(sign, today)
            text = f"🌟 *Персональный гороскоп* 🌟\n\n{horoscope}\n\n💫 *Хорошего дня!*"
            
            await bot.send_message(user_id, text)
            SENT_HOROSCOPES[today].add(user_id)
            sent_count += 1
            
            # Небольшая задержка между отправками
            await asyncio.sleep(0.1)
            
        except Exception as e:
            print(f"Error sending horoscope to {user_id}: {e}")
    
    print(f"📅 Отправлено {sent_count} гороскопов на {today}")

def reset_daily_horoscopes():
    """Сбросить счетчик отправленных гороскопов в полночь"""
    SENT_HOROSCOPES.clear()
    print("🔄 Счетчик гороскопов сброшен")

def schedule_daily_horoscopes():
    """Настроить расписание отправки гороскопов"""
    # Гороскопы в 08:00
    schedule.every().day.at("08:00").do(lambda: asyncio.run(send_daily_horoscopes()))
    
    # Сброс счетчика в полночь
    schedule.every().day.at("00:01").do(reset_daily_horoscopes)
    
    print("📅 Планировщик ежедневных гороскопов настроен (08:00)")

def run_scheduler():
    """Запустить планировщик в отдельном потоке"""
    while True:
        schedule.run_pending()
        time.sleep(60)  # Проверяем каждую минуту

