def ecl_long(body_name: str, dt: datetime) -> float:
    body = getattr(ephem, body_name)()
    body.compute(dt)
    ecl = ephem.Ecliptic(body)
    # возвращаем градусы в диапазоне [0, 360)
    lon = float(ecl.lon)
    if lon < 0:
        lon += 2 * math.pi
    return math.degrees(lon)

def is_retrograde(body_name: str, dt: datetime) -> bool:
    # сравниваем эклиптическую долготу cдвигом 24ч
    lon_today = ecl_long(body_name, dt)
    lon_tomorrow = ecl_long(body_name, dt + timedelta(days=1))
    # нормализуем разницу в диапазон (-180, +180)
    diff = (lon_tomorrow - lon_today + 540) % 360 - 180
    # если долгота уменьшается (движется назад по знакам) — ретроградность
    return diff < 0

