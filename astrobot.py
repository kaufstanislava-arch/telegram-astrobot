def compat_percent(a: str, b: str) -> int:
    if a == b: return 88
    ea, eb = ELEMENT.get(a,""), ELEMENT.get(b,"")
    if ea == eb:
        return 84
    pair = {ea, eb}
    if pair == {"Огонь","Воздух"}: return 82
    if pair == {"Земля","Вода"}: return 80
    if pair == {"Огонь","Вода"}: return 62
    if pair == {"Земля","Воздух"}: return 66
    return 72

