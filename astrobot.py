def zodiac_by_date(dt: datetime) -> str:
    mmdd = int(dt.strftime("%m%d"))
    for name, (start, end) in ZODIAC_RANGES:
        if start <= end:
            if start <= mmdd <= end:
                return name
        else:  # Козерог (перелом года)
            if mmdd >= start or mmdd <= end:
                return name
    return "Козерог"

