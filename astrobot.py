    # Рассчитываем следующие фазы Луны (упрощенный расчет)
    next_new_moon = today + timedelta(days=29 - (age % 29.5))
    next_full_moon = today + timedelta(days=14 - (age % 29.5))
    
    # Определяем ретроградные планеты (упрощенный расчет)
    retrograde_planets = []
    current_year = today.year
    
    # Меркурий ретрограден 3 раза в год примерно по 3 недели
    mercury_retro_dates = [
        (date(current_year, 1, 1), date(current_year, 1, 25)),
        (date(current_year, 4, 21), date(current_year, 5, 15)),
        (date(current_year, 8, 23), date(current_year, 9, 15)),
        (date(current_year, 12, 13), date(current_year, 12, 31))
    ]
    
    for start_date, end_date in mercury_retro_dates:
        if start_date <= today <= end_date:
            retrograde_planets.append("⚡ Меркурий ретрограден")
            break
    
