def calculate_lunar_node(birth_date, birth_time):
    """Рассчитывает Северный Лунный Узел"""
    try:
        # Создаем datetime объект
        dt = datetime.combine(birth_date, birth_time)
        
        # Конвертируем в UTC
        tz = pytz.timezone('UTC')
        dt_utc = tz.localize(dt)
        
        # Создаем время для astropy
        astro_time = Time(dt_utc)
        
        # Упрощенный расчет Северного Лунного Узла
        # В реальности нужен более точный алгоритм
        jd = astro_time.jd
        node_longitude = (125.044522 - 0.0529539 * (jd - 2451545.0)) % 360
        
        return node_longitude
    except Exception as e:
        print(f"Ошибка расчета Лунного узла: {e}")
        return None

