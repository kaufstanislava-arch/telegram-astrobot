    card = TAROT[unique_seed]
    
    # Определяем позицию карты (прямая/перевернутая) на основе ID и даты
    is_reversed = (user_id + today.day) % 2 == 0
    
    pos = "перевёрнутая" if is_reversed else "прямая"
    meaning = card["reversed"] if is_reversed else card["upright"]
    
    # Простое оформление карты дня
    text = (
        f"✨ *Карта дня* • {date_str}\n\n"
        f"🃏 *{card['name']}*\n"
        f"📖 {pos}\n\n"
        f"💫 *Совет на день:*\n{meaning}"
    )
    await c.message.edit_text(text, reply_markup=kb_back_home("home"))
    await c.answer()

