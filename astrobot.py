def format_date_russian(date_obj):
    """Форматировать дату на русском языке"""
    months = {
        1: "января", 2: "февраля", 3: "марта", 4: "апреля",
        5: "мая", 6: "июня", 7: "июля", 8: "августа",
        9: "сентября", 10: "октября", 11: "ноября", 12: "декабря"
    }
    return f"{date_obj.day} {months[date_obj.month]}"

def get_next_moon_phases():
    """Получить даты следующих фаз Луны"""
    today = date.today()
    # Упрощенный расчет (в реальности нужен точный астрономический расчет)
    next_new = today + timedelta(days=14)
    next_full = today + timedelta(days=7)
    return next_new, next_full

