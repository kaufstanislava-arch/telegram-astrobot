def calculate_ascendant_accurate(birth_date, birth_time, latitude, longitude):
    """Точный расчет Асцендента используя astropy"""
    try:
        # Создаем datetime объект
        dt = datetime.combine(birth_date, birth_time)
        
        # Конвертируем в UTC
        tz = pytz.timezone('UTC')
        dt_utc = tz.localize(dt)
        
        # Создаем время для astropy
        astro_time = Time(dt_utc)
        
        # Создаем местоположение
        location = EarthLocation(lat=latitude*u.deg, lon=longitude*u.deg)
        
        # Получаем Солнце
        sun = get_sun(astro_time)
        
        # Упрощенный расчет Асцендента
        # В реальности нужен более сложный алгоритм с учетом времени
        sun_longitude = sun.ra.to(u.deg).value
        ascendant_longitude = (sun_longitude + 90) % 360
        
        return ascendant_longitude
    except Exception as e:
        print(f"Ошибка расчета Асцендента: {e}")
        return None

def calculate_planets_accurate(birth_date, birth_time):
    """Точный расчет планет используя astropy"""
    try:
        # Создаем datetime объект
        dt = datetime.combine(birth_date, birth_time)
        
        # Конвертируем в UTC
        tz = pytz.timezone('UTC')
        dt_utc = tz.localize(dt)
        
        # Создаем время для astropy
        astro_time = Time(dt_utc)
        
        planets = {}
        
        # Солнце
        sun = get_sun(astro_time)
        sun_longitude = sun.ra.to(u.deg).value % 360
        planets['sun'] = sun_longitude
        
        # Луна
        moon = get_body('moon', astro_time)
        moon_longitude = moon.ra.to(u.deg).value % 360
        planets['moon'] = moon_longitude
        
        # Для других планет используем ephem как fallback
        observer = ephem.Observer()
        observer.date = ephem.Date(dt_utc)
        
        # Марс
        mars = ephem.Mars(observer)
        mars_longitude = math.degrees(mars.ra) % 360
        planets['mars'] = mars_longitude
        
        # Венера
        venus = ephem.Venus(observer)
        venus_longitude = math.degrees(venus.ra) % 360
        planets['venus'] = venus_longitude
        
        # Меркурий
        mercury = ephem.Mercury(observer)
        mercury_longitude = math.degrees(mercury.ra) % 360
        planets['mercury'] = mercury_longitude
        
        # Юпитер
        jupiter = ephem.Jupiter(observer)
        jupiter_longitude = math.degrees(jupiter.ra) % 360
        planets['jupiter'] = jupiter_longitude
        
        # Сатурн
        saturn = ephem.Saturn(observer)
        saturn_longitude = math.degrees(saturn.ra) % 360
        planets['saturn'] = saturn_longitude
        
        return planets
    except Exception as e:
        print(f"Ошибка расчета планет: {e}")
        return None

def calculate_natal_chart_accurate(birth_date, birth_time, latitude, longitude):
    """Рассчитывает натальную карту с высокой точностью"""
    try:
        # Рассчитываем Асцендент
        ascendant_longitude = calculate_ascendant_accurate(birth_date, birth_time, latitude, longitude)
        if ascendant_longitude is None:
            return None
        
        # Рассчитываем планеты
        planets = calculate_planets_accurate(birth_date, birth_time)
        if planets is None:
            return None
        
        # Определяем знаки зодиака
        ascendant_sign = get_zodiac_sign_by_longitude(ascendant_longitude)
        sun_sign = get_zodiac_sign_by_longitude(planets['sun'])
        moon_sign = get_zodiac_sign_by_longitude(planets['moon'])
        
        # Рассчитываем дополнительные элементы
        moon_phase, moon_phase_desc = get_moon_phase(planets['sun'], planets['moon'])
        ascendant_element = get_element_by_sign(ascendant_sign)
        ascendant_element_desc = get_element_description(ascendant_element)
        
        # Проверяем ретроградные планеты
        retrograde_planets = check_retrograde_planets(planets)
        
        # Рассчитываем Северный Лунный Узел
        lunar_node_longitude = calculate_lunar_node(birth_date, birth_time)
        lunar_node_sign = get_zodiac_sign_by_longitude(lunar_node_longitude) if lunar_node_longitude else "Неизвестно"
        
        # Рассчитываем MC
        mc_longitude = calculate_mc(birth_date, birth_time, latitude, longitude)
        mc_sign = get_zodiac_sign_by_longitude(mc_longitude) if mc_longitude else "Неизвестно"
        mc_description = get_mc_description(mc_sign)
        
        result = {
            'ascendant': {'sign': ascendant_sign, 'longitude': ascendant_longitude, 'element': ascendant_element, 'element_desc': ascendant_element_desc},
            'sun': {'sign': sun_sign, 'longitude': planets['sun']},
            'moon': {'sign': moon_sign, 'longitude': planets['moon'], 'phase': moon_phase, 'phase_desc': moon_phase_desc},
            'mars': {'sign': get_zodiac_sign_by_longitude(planets['mars']), 'longitude': planets['mars']},
            'venus': {'sign': get_zodiac_sign_by_longitude(planets['venus']), 'longitude': planets['venus']},
            'mercury': {'sign': get_zodiac_sign_by_longitude(planets['mercury']), 'longitude': planets['mercury']},
            'jupiter': {'sign': get_zodiac_sign_by_longitude(planets['jupiter']), 'longitude': planets['jupiter']},
            'saturn': {'sign': get_zodiac_sign_by_longitude(planets['saturn']), 'longitude': planets['saturn']},
            'lunar_node': {'sign': lunar_node_sign, 'longitude': lunar_node_longitude},
            'mc': {'sign': mc_sign, 'longitude': mc_longitude, 'description': mc_description},
            'retrograde_planets': retrograde_planets
        }
        
        return result
        
    except Exception as e:
        print(f"Ошибка расчета натальной карты: {e}")
        return None

