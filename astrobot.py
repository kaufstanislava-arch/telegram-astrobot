async def track_user_activity(user_id, action):
    """Упрощенное отслеживание активности пользователя"""
    try:
        # Минимальное отслеживание без сложных вычислений
        if user_id not in USER_ACTIVITY:
            USER_ACTIVITY[user_id] = {"actions": 0, "last_seen": datetime.now()}
        
        USER_ACTIVITY[user_id]["actions"] += 1
        USER_ACTIVITY[user_id]["last_seen"] = datetime.now()
        
        # Отправляем уведомление только для важных действий
        if action in ["Запуск бота (/start)", "Карта дня", "Случайный совет"]:
            await send_simple_notification(user_id, action)
    except:
        pass  # Игнорируем ошибки для стабильности

